"""Compare RepSelect's post-attack probability drop against the best baseline.

For each (model, dataset) cell of the main 3x5 grid we take the same statistic the
grid plot shows: the mean of the 10 lowest trial scores (post-attack answer
probability, lower is better). The drop is measured against the no-unlearning
reference run in baselines.yaml:

    drop = baseline - score

The "best baseline" is whichever of the five baseline methods achieves the largest
drop, i.e. the strongest competitor in that cell. The ratio is RepSelect's drop
divided by that.

Output: community/benchmarks/robustness_ratios.md
"""

import json
from pathlib import Path

import numpy as np
import yaml

BASE = Path(__file__).parent
OUT = BASE / "robustness_ratios.md"
TOP_N = 10

MODELS = ["Llama-3.1-8B", "Qwen3.5-9B", "DeepSeek-V2-Lite"]

# (subdir, results_dir, dataset_key, display_name)
DATASETS = [
    ("wmdp_low_mi", "results_bio", "bio", "WMDP-Bio"),
    ("wmdp_low_mi", "results_cyber", "cyber", "WMDP-Cyber"),
    ("rwku", "results", "rwku", "RWKU"),
    ("sycophancy", "results", "sycophancy", "Sycophancy"),
    ("beavertails", "results", "animal_abuse", "Animal Abuse"),
]

OURS = "RepSelectSimple_forget"
BASELINE_METHODS = ["GradDiff", "NPO", "RMU", "SimNPO", "UNDIAL"]

baselines = {}
for name in ["wmdp_low_mi", "beavertails", "rwku", "sycophancy"]:
    baselines.update(yaml.safe_load((BASE / name / "baselines.yaml").read_text()))


def score(subdir, results_dir, model, method):
    """Mean of the TOP_N lowest trial scores, as plotted in the main grid."""
    data = json.loads((BASE / subdir / results_dir / f"{model}.json").read_text())
    return float(np.mean(sorted(data[method]["scores"])[:TOP_N]))


rows = []
for subdir, results_dir, dataset, display in DATASETS:
    for model in MODELS:
        ref = baselines[dataset][model]
        ours = score(subdir, results_dir, model, OURS)
        best_method = min(
            BASELINE_METHODS, key=lambda m: score(subdir, results_dir, model, m)
        )
        best = score(subdir, results_dir, model, best_method)
        rows.append(
            dict(
                dataset=display,
                model=model,
                no_unlearning=ref,
                ours_score=ours,
                ours_drop=ref - ours,
                best_baseline=best_method,
                best_score=best,
                best_drop=ref - best,
                ratio=(ref - ours) / (ref - best),
            )
        )

lines = [
    "# RepSelect vs. best baseline: post-attack probability drops",
    "",
    "Generated by `robustness_ratios.py`.",
    f"Scores are the mean of the {TOP_N} lowest trials (as plotted in the main grid);",
    "lower is better.",
    "`drop = no-unlearning baseline - score`, so a larger drop means more robust forgetting.",
    "The best baseline is the one of GradDiff/NPO/RMU/SimNPO/UNDIAL with the largest drop.",
    "",
    "| Dataset | Model | No unlearning | RepSelect | RepSelect drop | Best baseline | Its score | Its drop | Ratio |",
    "|---|---|---|---|---|---|---|---|---|",
]
for r in rows:
    lines.append(
        f"| {r['dataset']} | {r['model']} | {r['no_unlearning']:.4f} | "
        f"{r['ours_score']:.4f} | {r['ours_drop']:.4f} | {r['best_baseline']} | "
        f"{r['best_score']:.4f} | {r['best_drop']:.4f} | {r['ratio']:.1f}x |"
    )

lines += ["", "## Ratio range per dataset", "", "| Dataset | Ratios | Range |", "|---|---|---|"]
for _, _, _, display in DATASETS:
    rs = [r["ratio"] for r in rows if r["dataset"] == display]
    lines.append(
        f"| {display} | {', '.join(f'{x:.1f}x' for x in rs)} | "
        f"{min(rs):.1f}–{max(rs):.1f}x |"
    )

all_ratios = [r["ratio"] for r in rows]
lines += [
    "",
    "## Overall",
    "",
    f"- {len(all_ratios)} cells, ratio range **{min(all_ratios):.1f}–{max(all_ratios):.1f}x**",
    f"- median {np.median(all_ratios):.1f}x, mean {np.mean(all_ratios):.1f}x",
    "",
]
OUT.write_text("\n".join(lines))
print("\n".join(lines))
print(f"\nwrote {OUT}")
